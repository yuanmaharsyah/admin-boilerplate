<?php

declare(strict_types=1);

namespace Yuan\AdminCore\Console;

use Illuminate\Console\Command;
use Illuminate\Filesystem\Filesystem;
use Illuminate\Support\Facades\Process;
use InvalidArgumentException;
use Yuan\AdminCore\Generator\ModuleBlueprint;
use Yuan\AdminCore\Generator\ModuleWriter;

/**
 * make:module (DEVELOPER R1): the whole module contract from the stubs, then
 * Pint and Prettier on it, `permissions:sync` and the type and route
 * generators. It never runs the migration.
 */
final class MakeModuleCommand extends Command
{
    public const string MARKER = '// Generated by make:module.';

    protected $signature = 'make:module
        {name : PascalCase, singular (Invoice)}
        {--fields= : name:type list, e.g. "number:string,issued_on:date,notes:text?,status:enum(draft,paid),customer_id:foreign(customers),scan:file(single,pdf,2048)"}
        {--actions=view,create,edit,delete,download : view is always included}
        {--group=master : a key of admin-core.menu.groups}
        {--icon=box : a lucide icon name}
        {--slug= : default: the kebab plural of the name}
        {--label= : default: the name}
        {--superadmin-only : no permissions; only Super Admin}
        {--force : overwrite a module folder make:module wrote, when git shows no changes in it}
        {--path= : the folder to write into (default: the project module root)}
        {--migration-date= : the migration file prefix (default: now, Y_m_d_His)}
        {--no-post : skip permissions:sync and the generators}
        {--no-sync : skip permissions:sync only (it writes to the database of the current .env)}
        {--allow-registered : skip the unique name / slug check (to regenerate a registered module elsewhere, e.g. the golden module check)}';

    protected $description = 'Generate a module with its full contract (admin-make-module skill)';

    public function handle(Filesystem $files): int
    {
        try {
            $module = ModuleBlueprint::make(
                name: $this->text('name'),
                fields: $this->stringOption('fields') ?? '',
                actions: explode(',', $this->stringOption('actions') ?? 'view'),
                group: $this->stringOption('group') ?? '',
                icon: $this->stringOption('icon') ?? '',
                slug: $this->stringOption('slug'),
                label: $this->stringOption('label'),
                superadminOnly: (bool) $this->option('superadmin-only'),
                checkRegistry: ! $this->option('allow-registered'),
            );
        } catch (InvalidArgumentException $exception) {
            $this->components->error($exception->getMessage());

            return self::FAILURE;
        }

        $folder = rtrim($this->stringOption('path') ?? ModuleBlueprint::projectRoot(), '/')."/{$module->name}";

        if ($files->exists($folder) && ! $this->mayOverwrite($files, $folder)) {
            return self::FAILURE;
        }

        $written = (new ModuleWriter($module, $this->stringOption('migration-date') ?? now()->format('Y_m_d_His')))->files();
        $files->deleteDirectory($folder);

        foreach ($written as $path => $contents) {
            $files->ensureDirectoryExists(dirname("{$folder}/{$path}"));
            $files->put("{$folder}/{$path}", $contents);
        }

        $this->format($folder);
        $this->components->info("Module {$module->name} written to {$folder} (".count($written).' files).');

        if (! $this->option('no-post')) {
            $this->postRun($module);
        }

        $this->nextSteps($module);

        return self::SUCCESS;
    }

    /** --force only replaces a folder this command wrote, with no uncommitted changes in it. */
    private function mayOverwrite(Filesystem $files, string $folder): bool
    {
        if (! $this->option('force')) {
            $this->components->error("{$folder} already exists. Pass --force to regenerate a module make:module wrote.");

            return false;
        }

        if (! str_contains((string) @file_get_contents("{$folder}/module.php"), self::MARKER)) {
            $this->components->error("{$folder} wasn't written by make:module; --force never overwrites it.");

            return false;
        }

        $status = Process::path($this->laravel->basePath())->run(['git', 'status', '--porcelain', '--', $folder]);

        if ($status->successful() && trim($status->output()) !== '') {
            $this->components->error("{$folder} has uncommitted changes; commit or discard them first.");

            return false;
        }

        return true;
    }

    /** Pint and Prettier, when the project has them, so the output is the same on every run. */
    private function format(string $folder): void
    {
        $base = $this->laravel->basePath();

        if (is_file("{$base}/vendor/bin/pint")) {
            Process::path($base)->run(['vendor/bin/pint', $folder]);
        }

        if (is_file("{$base}/node_modules/.bin/prettier")) {
            Process::path($base)->run(['node_modules/.bin/prettier', '--write', "{$folder}/resources/js"]);
        }
    }

    private function postRun(ModuleBlueprint $module): void
    {
        $steps = [
            ...($module->superadminOnly || $this->option('no-sync') ? [] : [['permissions:sync']]),
            ['modules:clear'],
            ['typescript:transform'],
            ['wayfinder:generate', '--with-form'],
        ];

        foreach ($steps as $step) {
            // A fresh process: this one booted before the module existed.
            $result = Process::path($this->laravel->basePath())->run([PHP_BINARY, 'artisan', ...$step]);
            $result->successful()
                ? $this->components->twoColumnDetail(implode(' ', $step), '<fg=green>done</>')
                : $this->components->twoColumnDetail(implode(' ', $step), '<fg=red>failed</> '.trim($result->errorOutput() ?: $result->output()));
        }
    }

    private function nextSteps(ModuleBlueprint $module): void
    {
        foreach ($module->unmaskedPersonalFields() as $field) {
            $this->components->warn("[{$field}] looks like personal data: add it to admin-core.audit.masked_fields (admin-audit skill).");
        }

        $this->components->bulletList([
            'Review the migration (indexes, onDelete), then: php artisan migrate',
            "Adjust the validation in Data/Store{$module->name}Data.php and Update{$module->name}Data.php",
            'Adjust the list columns in resources/js/pages/Index.tsx and the texts in resources/js/lang/*.ts',
            ...($this->option('no-sync') && ! $module->superadminOnly ? ['Create its permissions: php artisan permissions:sync'] : []),
            $module->superadminOnly ? 'Only Super Admin opens it (superadmin_only)' : 'Give a level access: Levels → Hak Akses',
        ]);
    }

    private function stringOption(string $name): ?string
    {
        $value = $this->option($name);

        return is_string($value) && $value !== '' ? $value : null;
    }

    private function text(string $argument): string
    {
        $value = $this->argument($argument);

        return is_string($value) ? $value : '';
    }
}
